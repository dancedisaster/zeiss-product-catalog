using Microsoft.AspNetCore.Http.HttpResults;
using ProductCatalog.Application.Products;

namespace ProductCatalog.Api.Endpoints;

internal static class ProductEndpoints
{
    private const string GetProductRoute = "GetProduct";

    public static IEndpointRouteBuilder MapProductEndpoints(this IEndpointRouteBuilder app)
    {
        var products = app.MapGroup("/api/products").WithTags("Products");

        // "{id:int}" keeps "/search" and "/stock-level" from being captured as an id.
        products.MapGet("/", ListAsync).WithSummary("List all products with their stock.");
        products.MapGet("/{id:int}", GetAsync).WithName(GetProductRoute).WithSummary("Get one product.");
        products.MapPost("/", CreateAsync).WithSummary("Create a product. The 6-digit id is generated by the server.");
        products.MapPut("/{id:int}", UpdateAsync).WithSummary("Update the details of a product (stock has its own endpoints).");
        products.MapDelete("/{id:int}", DeleteAsync).WithSummary("Delete a product.");
        products.MapPost("/{id:int}/decrement-stock/{quantity:int}", DecrementStockAsync).WithSummary("Remove units from stock.");
        products.MapPost("/{id:int}/add-to-stock/{quantity:int}", AddToStockAsync).WithSummary("Add units to stock.");
        products.MapGet("/search", SearchAsync).WithSummary("Find products whose name contains the given text.");
        products.MapGet("/stock-level", StockLevelAsync).WithSummary("List products with stock between min and max (inclusive).");

        return app;
    }

    private static async Task<Ok<IReadOnlyList<ProductDto>>> ListAsync(IProductService service, CancellationToken ct)
        => TypedResults.Ok(await service.ListAsync(ct));

    private static async Task<Results<Ok<ProductDto>, ProblemHttpResult>> GetAsync(int id, IProductService service, CancellationToken ct)
    {
        var result = await service.GetAsync(id, ct);
        return result.IsSuccess ? TypedResults.Ok(result.Value) : result.Error!.ToProblem();
    }

    private static async Task<Results<CreatedAtRoute<ProductDto>, ProblemHttpResult>> CreateAsync(
        CreateProductRequest request, IProductService service, CancellationToken ct)
    {
        var result = await service.CreateAsync(request, ct);
        return result.IsSuccess
            ? TypedResults.CreatedAtRoute(result.Value, GetProductRoute, new { id = result.Value.Id })
            : result.Error!.ToProblem();
    }

    private static async Task<Results<Ok<ProductDto>, ProblemHttpResult>> UpdateAsync(
        int id, UpdateProductRequest request, IProductService service, CancellationToken ct)
    {
        var result = await service.UpdateAsync(id, request, ct);
        return result.IsSuccess ? TypedResults.Ok(result.Value) : result.Error!.ToProblem();
    }

    private static async Task<Results<NoContent, ProblemHttpResult>> DeleteAsync(int id, IProductService service, CancellationToken ct)
    {
        var result = await service.DeleteAsync(id, ct);
        return result.IsSuccess ? TypedResults.NoContent() : result.Error!.ToProblem();
    }

    private static async Task<Results<Ok<ProductDto>, ProblemHttpResult>> DecrementStockAsync(
        int id, int quantity, IProductService service, CancellationToken ct)
    {
        var result = await service.DecrementStockAsync(id, quantity, ct);
        return result.IsSuccess ? TypedResults.Ok(result.Value) : result.Error!.ToProblem();
    }

    private static async Task<Results<Ok<ProductDto>, ProblemHttpResult>> AddToStockAsync(
        int id, int quantity, IProductService service, CancellationToken ct)
    {
        var result = await service.AddStockAsync(id, quantity, ct);
        return result.IsSuccess ? TypedResults.Ok(result.Value) : result.Error!.ToProblem();
    }

    private static async Task<Results<Ok<IReadOnlyList<ProductDto>>, ProblemHttpResult>> SearchAsync(
        string? name, IProductService service, CancellationToken ct)
    {
        var result = await service.SearchAsync(name, ct);
        return result.IsSuccess ? TypedResults.Ok(result.Value) : result.Error!.ToProblem();
    }

    private static async Task<Results<Ok<IReadOnlyList<ProductDto>>, ProblemHttpResult>> StockLevelAsync(
        int? min, int? max, IProductService service, CancellationToken ct)
    {
        var result = await service.ListByStockLevelAsync(min, max, ct);
        return result.IsSuccess ? TypedResults.Ok(result.Value) : result.Error!.ToProblem();
    }
}
