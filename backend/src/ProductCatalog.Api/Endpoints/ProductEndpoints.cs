using System.Globalization;
using Microsoft.AspNetCore.Http.HttpResults;
using ProductCatalog.Application.Products;

namespace ProductCatalog.Api.Endpoints;

internal static class ProductEndpoints
{
    /// <summary>Total number of matches across all pages, sent with every list response.</summary>
    public const string TotalCountHeader = "X-Total-Count";

    private const string GetProductRoute = "GetProduct";

    private const string PagingDescription =
        "Optional paging and sorting: page, pageSize (max 100), sortBy (name, categoryName, price, stock) and sortDir (asc, desc). " +
        "Without page/pageSize every match is returned. The X-Total-Count header holds the number of matches across all pages.";

    public static IEndpointRouteBuilder MapProductEndpoints(this IEndpointRouteBuilder app)
    {
        var products = app.MapGroup("/api/products").WithTags("Products");
        // The request timeout could fire after a write has committed, and the client would be told it failed
        // (DECISIONS 16). Writes are short, and each SQL command still has its own timeout.
        var writes = products.MapGroup(string.Empty);
        writes.DisableRequestTimeout();

        // "{id:int}" keeps "/search", "/stock-level" and "/summary" from being captured as an id.
        products.MapGet("/", ListAsync).WithSummary("List all products with their stock.").WithDescription(PagingDescription);
        products.MapGet("/summary", SummaryAsync).WithSummary("Catalogue-wide counts: products, units in stock, low stock, out of stock.");
        products.MapGet("/{id:int}", GetAsync).WithName(GetProductRoute).WithSummary("Get one product.");
        writes.MapPost("/", CreateAsync).WithSummary("Create a product. The 6-digit id is generated by the server.");
        writes.MapPut("/{id:int}", UpdateAsync).WithSummary("Update the details of a product (stock has its own endpoints).");
        writes.MapDelete("/{id:int}", DeleteAsync).WithSummary("Delete a product.");
        writes.MapPost("/{id:int}/decrement-stock/{quantity:int}", DecrementStockAsync).WithSummary("Remove units from stock.");
        writes.MapPost("/{id:int}/add-to-stock/{quantity:int}", AddToStockAsync).WithSummary("Add units to stock.");
        products.MapGet("/search", SearchAsync)
            .WithSummary("Find products whose name contains the given text, optionally within a stock range (min, max).")
            .WithDescription(PagingDescription);
        products.MapGet("/stock-level", StockLevelAsync)
            .WithSummary("List products with stock between min and max (inclusive).")
            .WithDescription(PagingDescription);

        return app;
    }

    private static async Task<Results<Ok<IReadOnlyList<ProductDto>>, ProblemHttpResult>> ListAsync(
        [AsParameters] ListOptions options, IProductService service, HttpResponse response, CancellationToken ct)
    {
        var result = await service.ListAsync(options, ct);
        return result.IsSuccess ? Page(result.Value, response) : result.Error!.ToProblem();
    }

    private static async Task<Ok<ProductSummary>> SummaryAsync(IProductService service, CancellationToken ct)
        => TypedResults.Ok(await service.GetSummaryAsync(ct));

    private static async Task<Results<Ok<ProductDto>, ProblemHttpResult>> GetAsync(int id, IProductService service, CancellationToken ct)
    {
        var result = await service.GetAsync(id, ct);
        return result.IsSuccess ? TypedResults.Ok(result.Value) : result.Error!.ToProblem();
    }

    private static async Task<Results<CreatedAtRoute<ProductDto>, ProblemHttpResult>> CreateAsync(
        CreateProductRequest request, IProductService service, CancellationToken ct)
    {
        var result = await service.CreateAsync(request, ct);
        return result.IsSuccess
            ? TypedResults.CreatedAtRoute(result.Value, GetProductRoute, new { id = result.Value.Id })
            : result.Error!.ToProblem();
    }

    private static async Task<Results<Ok<ProductDto>, ProblemHttpResult>> UpdateAsync(
        int id, UpdateProductRequest request, IProductService service, CancellationToken ct)
    {
        var result = await service.UpdateAsync(id, request, ct);
        return result.IsSuccess ? TypedResults.Ok(result.Value) : result.Error!.ToProblem();
    }

    private static async Task<Results<NoContent, ProblemHttpResult>> DeleteAsync(int id, IProductService service, CancellationToken ct)
    {
        var result = await service.DeleteAsync(id, ct);
        return result.IsSuccess ? TypedResults.NoContent() : result.Error!.ToProblem();
    }

    private static async Task<Results<Ok<ProductDto>, ProblemHttpResult>> DecrementStockAsync(
        int id, int quantity, IProductService service, CancellationToken ct)
    {
        var result = await service.DecrementStockAsync(id, quantity, ct);
        return result.IsSuccess ? TypedResults.Ok(result.Value) : result.Error!.ToProblem();
    }

    private static async Task<Results<Ok<ProductDto>, ProblemHttpResult>> AddToStockAsync(
        int id, int quantity, IProductService service, CancellationToken ct)
    {
        var result = await service.AddStockAsync(id, quantity, ct);
        return result.IsSuccess ? TypedResults.Ok(result.Value) : result.Error!.ToProblem();
    }

    private static async Task<Results<Ok<IReadOnlyList<ProductDto>>, ProblemHttpResult>> SearchAsync(
        string? name, int? min, int? max, [AsParameters] ListOptions options, IProductService service, HttpResponse response, CancellationToken ct)
    {
        var result = await service.SearchAsync(name, min, max, options, ct);
        return result.IsSuccess ? Page(result.Value, response) : result.Error!.ToProblem();
    }

    private static async Task<Results<Ok<IReadOnlyList<ProductDto>>, ProblemHttpResult>> StockLevelAsync(
        int? min, int? max, [AsParameters] ListOptions options, IProductService service, HttpResponse response, CancellationToken ct)
    {
        var result = await service.ListByStockLevelAsync(min, max, options, ct);
        return result.IsSuccess ? Page(result.Value, response) : result.Error!.ToProblem();
    }

    /// <summary>The body stays a plain array (the required contract); the total travels in a header.</summary>
    private static Ok<IReadOnlyList<ProductDto>> Page(ProductPage page, HttpResponse response)
    {
        response.Headers[TotalCountHeader] = page.TotalCount.ToString(CultureInfo.InvariantCulture);
        return TypedResults.Ok(page.Items);
    }
}
